#!/usr/bin/env python3
"""Evaluate unseen classes on image-disjoint data with an explicit split audit.

Closed-set mAP (val1k.yaml, all 80 classes) only reflects detection quality on
training classes, while the core capability of an OV detector is **generalizing
text prompts to unseen classes**. This script:

  1. deterministically splits the 80 COCO classes into seen/unseen
     from a shared ``class_split.json`` generated by ``make_class_split.py``;
  2. rejects overlap between training and evaluation manifests;
  3. builds unseen-only labels for every image in the evaluation manifest,
     including empty labels for images without unseen objects;
  4. sets the text prompts with ``set_classes(unseen_names)`` and runs
     ``model.val`` to obtain unseen-class mAP50 / mAP50-95 -- the true
     open-vocabulary metrics.

Usage:
  python scripts/ov_distill/eval_ov_holdout.py \
      --weights runs/ov_s2_train/s5k_q16/weights/best.pt \
      --labels runs/ov_s2_5k/gt_labels --images datasets/coco/val2017 \
      --train-manifest runs/ov_s2_20k/train_manifest.jsonl \
      --eval-manifest runs/ov_s2_20k/val_manifest.jsonl \
      --class-split runs/ov_distill/class_split.json \
      --out runs/ov_s2_5k/ov_holdout --device mps

The manifests must have no canonical-path overlap. Evaluation-manifest images
must live directly in ``--images`` because the label files are matched by
basename. The training manifest may use a different image root.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import List, Tuple

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from scripts.ov_distill.class_split import build_class_split, load_class_split  # noqa: E402
from scripts.ov_distill.make_coco128_manifest import COCO_NAMES  # noqa: E402
from scripts.ov_distill.reliability import assert_disjoint_manifests  # noqa: E402


def split_classes(unseen_ratio: float = 0.25, seed: int = 0) -> Tuple[List[str], List[str]]:
    """Split class names deterministically, independently of COCO class-id order."""
    split = build_class_split(unseen_ratio=unseen_ratio, seed=seed)
    return split["seen"], split["unseen"]


def build_unseen_val(
    labels: Path,
    images: Path,
    out: Path,
    unseen: List[str],
    eval_images: set[str],
    max_images: int = 0,
) -> Path:
    """Build an unseen-only validation set from explicit, image-disjoint evaluation files.

    Returns:
        Path of the generated data yaml.
    """
    name2old = {n: i for i, n in enumerate(COCO_NAMES)}
    remap = {name2old[n]: i for i, n in enumerate(unseen)}
    out_labels = out / "val" / "labels"
    out_images = out / "val" / "images"
    for output_dir in (out_labels, out_images):
        if output_dir.exists() and any(output_dir.iterdir()):
            raise FileExistsError(f"refusing to mix a new split with existing files in {output_dir}")
    out_labels.mkdir(parents=True, exist_ok=True)
    out_images.mkdir(parents=True, exist_ok=True)
    image_root = Path(images).resolve()
    image_paths = [Path(image).resolve() for image in sorted(eval_images)]
    if max_images < 0:
        raise ValueError(f"max_images must be non-negative, got {max_images}")
    if max_images:
        image_paths = image_paths[:max_images]
    stems = [image.stem for image in image_paths]
    if len(stems) != len(set(stems)):
        raise ValueError("evaluation manifest contains duplicate image basenames; label mapping would be ambiguous")
    for image in image_paths:
        if image.parent != image_root:
            raise ValueError(f"evaluation image must be directly inside --images: {image}")
        if not image.is_file():
            raise FileNotFoundError(f"evaluation image does not exist: {image}")

    for image in image_paths:
        lab = Path(labels) / f"{image.stem}.txt"
        lines = []
        source_lines = lab.read_text(encoding="utf-8").splitlines() if lab.is_file() else []
        for line in source_lines:
            p = line.split()
            if len(p) < 5:
                continue
            cid = int(p[0])
            if cid in remap:
                lines.append(f"{remap[cid]} " + " ".join(p[1:5]))
        # Keep empty labels: they measure false positives on images with no unseen-class objects.
        (out_labels / f"{image.stem}.txt").write_text("\n".join(lines) + ("\n" if lines else ""), encoding="utf-8")
        dst = out_images / image.name
        if not dst.exists():
            dst.symlink_to(image)

    yaml_path = out / "ov_unseen.yaml"
    names_yaml = "\n".join(f"  {i}: {n}" for i, n in enumerate(unseen))
    yaml_path.write_text(
        # check_det_dataset mandates a train key; placeholder only, never read during validation
        f"path: {out.resolve()}\ntrain: val/images\nval: val/images\nnames:\n{names_yaml}\n",
        encoding="utf-8",
    )
    return yaml_path


def main() -> None:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description="OV seen/unseen class-split evaluation")
    parser.add_argument("--weights", default="", help="model checkpoint; not needed with --build-only")
    parser.add_argument("--labels", required=True, help="full GT label directory (YOLO txt, COCO 80-class ids)")
    parser.add_argument("--images", required=True, help="image directory (.jpg files matching label names)")
    parser.add_argument("--train-manifest", required=True, help="training image manifest used for the model")
    parser.add_argument(
        "--eval-manifest", required=True, help="held-out image manifest represented by --images/--labels"
    )
    parser.add_argument("--out", required=True, help="output directory (unseen validation set + results)")
    parser.add_argument("--class-split", required=True, help="same COCO-80 split JSON used to filter training labels")
    parser.add_argument("--max-images", type=int, default=0, help="limit the number of validation images (0 = all)")
    parser.add_argument("--imgsz", type=int, default=384)
    parser.add_argument("--batch", type=int, default=8)
    parser.add_argument("--device", default="cpu")
    parser.add_argument("--build-only", action="store_true", help="only build the unseen validation set; skip val")
    args = parser.parse_args()

    train_images, eval_images = assert_disjoint_manifests(
        Path(args.train_manifest), Path(args.eval_manifest), first_name="training", second_name="evaluation"
    )

    class_split = load_class_split(Path(args.class_split))
    seen, unseen = class_split["seen"], class_split["unseen"]
    print(f"[ov-holdout] seen={len(seen)} unseen={len(unseen)}: {unseen}")

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    yaml_path = build_unseen_val(
        Path(args.labels), Path(args.images), out, unseen, eval_images=eval_images, max_images=args.max_images
    )
    evaluated_images = min(args.max_images, len(eval_images)) if args.max_images else len(eval_images)
    split_report = {
        "train_manifest": str(Path(args.train_manifest).resolve()),
        "eval_manifest": str(Path(args.eval_manifest).resolve()),
        "class_split": str(Path(args.class_split).resolve()),
        "class_split_seed": class_split.get("seed"),
        "seen_classes": seen,
        "unseen_classes": unseen,
        "train_images": len(train_images),
        "eval_manifest_images": len(eval_images),
        "evaluated_images": evaluated_images,
        "image_overlap": 0,
    }
    (out / "split_audit.json").write_text(json.dumps(split_report, indent=2) + "\n", encoding="utf-8")
    print(f"[ov-holdout] unseen val yaml: {yaml_path}")
    print(f"[ov-holdout] split audit: {json.dumps(split_report, ensure_ascii=False)}")

    if args.build_only:
        return

    if not args.weights:
        parser.error("--weights is required unless --build-only is set")

    from ultralytics import YOLOE

    model = YOLOE(args.weights)
    model.set_classes(unseen, model.get_text_pe(unseen))
    r = model.val(
        data=str(yaml_path),
        imgsz=args.imgsz,
        batch=args.batch,
        device=args.device,
        project=str(out),
        name="val_unseen",
        exist_ok=True,
        verbose=False,
        plots=False,
    )
    report = {
        "weights": args.weights,
        "unseen_classes": unseen,
        "n_unseen": len(unseen),
        "mAP50": round(float(r.box.map50), 4),
        "mAP50-95": round(float(r.box.map), 4),
        "precision": round(float(r.box.mp), 4),
        "recall": round(float(r.box.mr), 4),
        **split_report,
    }
    (out / "ov_holdout_report.json").write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
